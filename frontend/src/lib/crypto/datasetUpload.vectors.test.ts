// The cross-implementation upload vector: a dataset upload body sealed by
// the browser's own code, which `platform-api`'s
// `a_browser_sealed_upload_opens_in_the_enclave` stores through the upload
// route and queries, opening both envelopes with the backend's open path
// and checking the declared schema in the enclave.
//
// Sealing is randomized, so the body is written once and committed:
//
//   WRITE_UPLOAD_VECTORS=1 npx vitest run --project node src/lib/crypto/datasetUpload.vectors.test.ts
//
// Without the variable, this checks the committed body from the browser's
// side: it declares what the footer reader reads, and opens here.

import { afterEach, beforeAll, describe, expect, it, vi } from "vitest";

import recipients from "../../../../fixtures/envelope/hpk1.json";
import { parquetFixture } from "../../test/parquetFixtures";
import { readFooter } from "../datasets/footer";
import { fromB64, toB64 } from "../encoding";
import { uploadDataset } from "./datasetUpload";
import { envelopeInfo, loadEnvelopeModule, openWithPrivateKey } from "./envelope";
import envelopeWasmInline from "./wasm/envelope_bg.wasm?url&inline";

const VECTOR = "../../../../fixtures/envelope/hpk1-browser-upload.json";
const committed = import.meta.glob<UploadVector>("../../../../fixtures/envelope/hpk1-browser-upload.json", {
  eager: true,
  import: "default",
})[VECTOR];

interface UploadVector {
  description: string;
  recipient: string;
  tenant: string;
  dataset: string;
  parquet: string;
  version: string;
  object: string;
  row_cap: number;
  schema: unknown;
  body_b64: string;
}

const PARQUET = "upload-cohort.parquet";
const TENANT = "6f2c8a2e-1111-4222-8333-444455556666";
const DATASET = "upload_cohorts";
const recipient = recipients.recipients.find((r) => r.name === "a")!;

const env = (globalThis as { process?: { env?: Record<string, string | undefined> } }).process?.env ?? {};

beforeAll(async () => {
  await loadEnvelopeModule(envelopeWasmInline);
});

afterEach(() => {
  vi.unstubAllGlobals();
});

/** Seals the cohort as the worker does and returns the vector. */
async function seal(): Promise<UploadVector> {
  const file = new File([parquetFixture(PARQUET)], PARQUET);
  const reading = await readFooter(file);
  if (!reading.ok) throw new Error(reading.refusal.code);
  let body: Uint8Array | undefined;
  vi.stubGlobal(
    "fetch",
    vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      if (String(input).endsWith("/enrollment")) {
        return new Response(JSON.stringify({ hpke_public_key_b64: recipient.public_b64 }));
      }
      body = new Uint8Array(await (init!.body as Blob).arrayBuffer());
      const header = JSON.parse(new TextDecoder().decode(body.subarray(8, 8 + new DataView(body.buffer).getUint32(4))));
      return new Response(JSON.stringify({ dataset: DATASET, version: header.version, object: header.object, suite: "HPK1" }));
    }),
  );
  const result = await uploadDataset(
    {
      keys: {
        identity: { iss: "local", sub: "local", tid: "local-device-id" },
        tenantId: "local-device-id",
        kek: {} as CryptoKey,
        hpke: {
          seedKey: {} as CryptoKey,
          publicKeyRaw: fromB64(recipient.public_b64),
          sealedPrivateKey: { iv: new ArrayBuffer(12), data: new ArrayBuffer(48) },
        },
        createdAtIso: "2026-11-21T00:00:00.000Z",
      },
      session: { token: "t", claims: { iss: "dev", sub: "steward", tid: TENANT } },
      apiBaseUrl: "",
    },
    {
      file,
      dataset: DATASET,
      schema: reading.schema,
      rowCap: reading.rows,
      currentVersion: null,
      maxBytes: 64 * 1024 * 1024,
    },
  );
  return {
    description:
      "A dataset upload body (DSU1, ADR 0012) sealed by the browser's upload code (frontend/src/lib/crypto/datasetUpload.ts) " +
      "to test-only recipient a of hpk1.json: the synthetic cohort in fixtures/parquet/upload-cohort.parquet, declared as the " +
      "browser's footer reader reads it. backend/crates/platform-api/tests/dataset_upload_api.rs stores it through the upload " +
      "route and queries it. Generated by frontend/src/lib/crypto/datasetUpload.vectors.test.ts with WRITE_UPLOAD_VECTORS=1; " +
      "sealing is randomized, so regenerating changes the bytes, not what they open to.",
    recipient: "a",
    tenant: TENANT,
    dataset: DATASET,
    parquet: PARQUET,
    version: result.version,
    object: result.object,
    row_cap: reading.rows,
    schema: reading.schema,
    body_b64: toB64(body!.buffer as ArrayBuffer),
  };
}

describe("the browser-sealed upload vector", () => {
  it.runIf(env.WRITE_UPLOAD_VECTORS === "1")("writes the vector", async () => {
    const vector = await seal();
    const fs = (await import("node:fs" as string)) as { writeFileSync(path: URL, data: string): void };
    fs.writeFileSync(new URL(VECTOR, import.meta.url), `${JSON.stringify(vector, null, 2)}\n`);
  });

  it.runIf(env.WRITE_UPLOAD_VECTORS !== "1")("declares what the footer reads and opens here", async () => {
    expect(committed, "the vector is committed").toBeDefined();
    const vector = committed!;
    const reading = await readFooter(new Blob([parquetFixture(vector.parquet)]));
    expect(reading).toMatchObject({ ok: true, schema: vector.schema, rows: vector.row_cap });

    const body = new Uint8Array(fromB64(vector.body_b64));
    const view = new DataView(body.buffer);
    expect(new TextDecoder().decode(body.subarray(0, 4))).toBe("DSU1");
    const headerLength = view.getUint32(4);
    const header = JSON.parse(new TextDecoder().decode(body.subarray(8, 8 + headerLength)));
    expect(header).toEqual({
      version: vector.version,
      object: vector.object,
      row_cap: vector.row_cap,
      schema: vector.schema,
    });
    const manifestLength = view.getUint32(8 + headerLength);
    const manifest = body.slice(12 + headerLength, 12 + headerLength + manifestLength);
    const object = body.slice(12 + headerLength + manifestLength);
    const key = () => new Uint8Array(fromB64(recipient.private_b64_test_only));
    const parquet = await openWithPrivateKey(
      key(),
      await envelopeInfo.stewardUpload(vector.tenant, vector.dataset, vector.object),
      object.buffer,
    );
    expect(new Uint8Array(parquet)).toEqual(parquetFixture(vector.parquet));
    const listed = await openWithPrivateKey(
      key(),
      await envelopeInfo.snapshotManifest(vector.tenant, vector.dataset, vector.version),
      manifest.buffer,
    );
    expect(JSON.parse(new TextDecoder().decode(listed))).toEqual({
      version: vector.version,
      objects: [vector.object],
    });
  });
});
