// Writes fixtures/envelope/hpk1-browser-sealed.json: envelopes sealed by the
// browser's wasm module, which backend/crates/envelope-wasm/tests/vectors.rs
// must open. Recipients and info strings come from fixtures/envelope/hpk1.json,
// so every key is test-only. Sealing is randomized: rerunning changes the
// bytes, not whether they open.
//
// Run after scripts/build-wasm.sh, from frontend/:
//   node scripts/browser-sealed-vectors.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { initSync, researchResultInfo, sealEnvelope, stewardUploadInfo } from "../src/lib/crypto/wasm/envelope.js";

const fixtures = new URL("../../fixtures/envelope/", import.meta.url);
const vectors = JSON.parse(readFileSync(new URL("hpk1.json", fixtures), "utf8"));
initSync({ module: readFileSync(new URL("../src/lib/crypto/wasm/envelope_bg.wasm", import.meta.url)) });

const publicKey = (name) =>
  Buffer.from(vectors.recipients.find((r) => r.name === name).public_b64, "base64");
const fields = (kind) => vectors.info.find((v) => v.kind === kind).fields;
const text = (bytes) => new TextDecoder().decode(bytes);

const cases = [
  { recipient: "a", info: stewardUploadInfo(...fields("steward_upload")), plaintext: "synthetic cohort rows: site-a,42\n" },
  { recipient: "b", info: researchResultInfo(...fields("research_result")), plaintext: "synthetic result: n=42" },
  { recipient: "a", info: stewardUploadInfo(...fields("steward_upload")), plaintext: "" },
];

const envelopes = cases.map(({ recipient, info, plaintext }) => ({
  recipient,
  info: text(info),
  plaintext,
  envelope_b64: Buffer.from(
    sealEnvelope(publicKey(recipient), info, new TextEncoder().encode(plaintext)),
  ).toString("base64"),
}));

const out = {
  description:
    "HPK1 envelopes sealed by the browser's wasm module. Test-only recipients from hpk1.json. Generated by frontend/scripts/browser-sealed-vectors.mjs.",
  envelopes,
};
writeFileSync(new URL("hpk1-browser-sealed.json", fixtures), `${JSON.stringify(out, null, 2)}\n`);
